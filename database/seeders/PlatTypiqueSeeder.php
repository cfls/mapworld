    public function run(): void
    {
        $notFound = [];

        foreach (self::PLATS as $docxName => $plat) {
            $dbName = self::NAME_ALIASES[$docxName] ?? $docxName;
            $country = Country::where('name', $dbName)->first();

            if (! $country) {
                $notFound[] = $docxName;

                continue;
            }

            $country->info()->updateOrCreate(
                ['country_id' => $country->id],
                ['plat_typique' => $plat]
            );
        }

        if ($notFound !== []) {
            $this->command->warn('Pays non trouvés : '.implode(', ', $notFound));
        }
    }
